  }

  signingConfigs {
    create("release") {
      // Credentials come from keystore.properties (gitignored) so a plain
      // `./gradlew assembleRelease` — or a Build > Generate Signed APK from Android Studio —
      // signs correctly with no environment set up. Env vars still win for CI.
      val props = Properties().apply {
        val file = rootProject.file("keystore.properties")
        if (file.exists()) file.inputStream().use { load(it) }
      }
      fun setting(key: String, env: String): String? =
        System.getenv(env) ?: props.getProperty(key)

      // Relative paths resolve against the repo root, not the app module.
      storeFile = rootProject.file(setting("storeFile", "KEYSTORE_PATH") ?: "client-test-key.jks")
      storePassword = setting("storePassword", "STORE_PASSWORD")
      keyAlias = setting("keyAlias", "KEY_ALIAS") ?: "upload"
      keyPassword = setting("keyPassword", "KEY_PASSWORD")
    }
    create("debugConfig") {
      storeFile = file("${rootDir}/debug.keystore")
      storePassword = "android"
      keyAlias = "androiddebugkey"
      keyPassword = "android"
    }
  }

  buildTypes {
    release {
      isCrunchPngs = false
      isMinifyEnabled = false
      proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
      signingConfig = signingConfigs.getByName("release")
    }
